const hre=require('hardhat'),{ethers}=require('ethers'),b=require('./build.json');
const U=n=>ethers.parseUnits(String(n),6), f=x=>ethers.formatUnits(x,6);
let pass=0,fail=0;const ok=(c,m)=>{if(c){pass++;console.log('  ✓',m)}else{fail++;console.log('  ✗',m)}};
async function reverts(p,msg){try{await (await p).wait?.();return false}catch(e){return (e.message||'').includes(msg)}}
(async()=>{
 const g=hre.network.provider;
 const p=new ethers.BrowserProvider(g,undefined,{cacheTimeout:-1});
 const [owner,inv,biz,debtor,other]=await Promise.all([0,1,2,3,4].map(i=>p.getSigner(i)));

 const dep=async(c,s,...a)=>{const F=new ethers.ContractFactory(c.abi,c.evm.bytecode.object,s);const x=await F.deploy(...a);await x.waitForDeployment();return x};
 const usdc=await dep(b['MockUSDC.sol'].MockUSDC,owner);
 const fac=await dep(b['InvoiceFactoring.sol'].InvoiceFactoring,owner,await usdc.getAddress());
 const FA=await fac.getAddress();
 for(const s of [owner,inv,biz,debtor,other]) await (await usdc.mint(await s.getAddress(),U(100000))).wait();
 const now=async()=>Number((await p.send('eth_getBlockByNumber',['latest',false])).timestamp);
 const warp=async s=>{await p.send('evm_increaseTime',[s]);await p.send('evm_mine',[])};
 console.log('Pool');
 await (await usdc.connect(inv).approve(FA,U(50000))).wait();
 await (await fac.connect(inv).deposit(U(50000))).wait();
 ok((await fac.totalAssets())==U(50000),'investor deposits $50,000, totalAssets = 50000');
 console.log('Happy path: $10,000 invoice, 60 days, 85% advance, 1.5%/30d');
 const fp=await fac.computeFingerprint('BN123','BN999','INV-1001',U(10000),1763300000);
 const due=(await now())+60*86400;
 await (await fac.connect(biz).registerInvoice(await debtor.getAddress(),U(10000),due,fp,'INV-1001')).wait();
 ok(await reverts(fac.connect(biz).registerInvoice(await debtor.getAddress(),U(10000),due,fp,'INV-1001 again'),'Duplicate invoice'),'duplicate fingerprint rejected (double-financing blocked)');
 ok(await reverts(fac.setOffer(0,8500,150),'Debtor has not confirmed'),'cannot make offer before debtor confirms');
 ok(await reverts(fac.connect(other).confirmInvoice(0),'Only the debtor'),'only debtor can confirm');
 await (await fac.connect(debtor).confirmInvoice(0)).wait();
 ok(await reverts(fac.setOffer(0,9500,150),'Advance % over limit'),'advance over 90% cap rejected');
 ok(await reverts(fac.connect(other).setOffer(0,8500,150),'Not owner'),'only underwriter sets offers');
 await (await fac.setOffer(0,8500,150)).wait();
 let i0=await fac.getInvoice(0);
 ok(i0.advanceAmount==U(8500),'advance = $'+f(i0.advanceAmount));
 ok(i0.feeAmount==U(255),'fee = $'+f(i0.feeAmount)+' (1.5% x 2 months on the $8,500 advanced)');
 const b0=await usdc.balanceOf(await biz.getAddress());
 await (await fac.connect(biz).acceptOffer(0)).wait();
 ok((await usdc.balanceOf(await biz.getAddress()))-b0==U(8500),'business receives $8,500 immediately');
 ok((await fac.outstandingPrincipal())==U(8500),'outstanding principal tracked');
 ok(await reverts(fac.markDefault(0),'Grace period not over'),'cannot default before due + grace');
 await warp(59*86400);
 await (await usdc.connect(debtor).approve(FA,U(10000))).wait();
 const b1=await usdc.balanceOf(await biz.getAddress());
 await (await fac.connect(debtor).repay(0)).wait();
 ok((await usdc.balanceOf(await biz.getAddress()))-b1==U(1245),'business gets remaining $'+f((await usdc.balanceOf(await biz.getAddress()))-b1));
 ok((await fac.totalAssets())==U(50255),'pool grows to $'+f(await fac.totalAssets()));
 ok((await fac.sharePrice())>U(1),'share price up: $'+f(await fac.sharePrice()));
 console.log('Default path with first-loss fund');
 await (await usdc.connect(owner).approve(FA,U(2000))).wait();
 await (await fac.depositFirstLoss(U(2000))).wait();
 const fp2=await fac.computeFingerprint('BN123','BN888','INV-2002',U(10000),1763300000);
 const due2=(await now())+30*86400;
 await (await fac.connect(biz).registerInvoice(await other.getAddress(),U(10000),due2,fp2,'INV-2002')).wait();
 await (await fac.connect(other).confirmInvoice(1)).wait();
 await (await fac.setOffer(1,8000,200)).wait();
 await (await fac.connect(biz).acceptOffer(1)).wait();
 await warp(61*86400);
 await (await fac.markDefault(1)).wait();
 ok((await fac.firstLossFund())==0n,'first-loss fund ($2,000) absorbed first');
 ok((await fac.totalLosses())==U(6000),'pool loss = $'+f(await fac.totalLosses()));
 const i1=await fac.getInvoice(1);
 console.log('Late recovery');
 await (await usdc.connect(other).approve(FA,U(10000))).wait();
 const ta=await fac.totalAssets();
 await (await fac.connect(other).repay(1)).wait();
 ok((await fac.totalLosses())==0n,'pool loss fully recovered');
 ok((await fac.firstLossFund())==U(2000),'first-loss fund refilled');
 ok((await fac.totalAssets())-ta==U(6000)+i1.feeAmount,'pool regains loss + fee');
 console.log('Withdraw');
 const sh=await fac.shares(await inv.getAddress());
 const before=await usdc.balanceOf(await inv.getAddress());
 await (await fac.connect(inv).withdraw(sh)).wait();
 const got=(await usdc.balanceOf(await inv.getAddress()))-before;
 ok(got>U(50000),'investor withdraws $'+f(got)+' (deposit + fees)');
 ok((await usdc.balanceOf(FA))==(await fac.firstLossFund())+(await fac.idleCash()),'contract balance reconciles to idle cash + first-loss fund');
 console.log(`\n${pass} passed, ${fail} failed`);process.exit(fail?1:0);
})().catch(e=>{console.error(e);process.exit(1)});
